// Encode UTF-8 bytes through CP1251 table (bytes->unicode string)
function bytesViaCP1251(buf){
  let s='';
  for(const b of buf) s+=String.fromCodePoint(T[b]??b);
  return s;
}

// Triple-encode a correct Ukrainian string (simulates what PowerShell did twice)
function tripleEncode(s){
  const b1=Buffer.from(s,'utf8');
  const s1=bytesViaCP1251(b1);
  const b2=Buffer.from(s1,'utf8');
  return bytesViaCP1251(b2);
}

