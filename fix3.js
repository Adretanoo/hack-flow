const fs = require('fs');
// Build CP1251 byte→Unicode map
const CP = [
  0x0402,0x0403,0x201A,0x0453,0x201E,0x2026,0x2020,0x2021,0x20AC,0x2030,0x0409,0x2039,0x040A,0x040C,0x040B,0x040F,
  0x0452,0x2018,0x2019,0x201C,0x201D,0x2022,0x2013,0x2014,null,0x2122,0x0459,0x203A,0x045A,0x045D,0x045B,0x045F,
  0x00A0,0x040E,0x045E,0x0408,0x00A4,0x0490,0x00A6,0x00A7,0x0401,0x00A9,0x0404,0x00AB,0x00AC,0x00AD,0x00AE,0x0407,
  0x00B0,0x00B1,0x0406,0x0456,0x0491,0x00B5,0x00B6,0x00B7,0x0451,0x2116,0x0454,0x00BB,0x0458,0x0405,0x0455,0x0457,
  0x0410,0x0411,0x0412,0x0413,0x0414,0x0415,0x0416,0x0417,0x0418,0x0419,0x041A,0x041B,0x041C,0x041D,0x041E,0x041F,
  0x0420,0x0421,0x0422,0x0423,0x0424,0x0425,0x0426,0x0427,0x0428,0x0429,0x042A,0x042B,0x042C,0x042D,0x042E,0x042F,
  0x0430,0x0431,0x0432,0x0433,0x0434,0x0435,0x0436,0x0437,0x0438,0x0439,0x043A,0x043B,0x043C,0x043D,0x043E,0x043F,
  0x0440,0x0441,0x0442,0x0443,0x0444,0x0445,0x0446,0x0447,0x0448,0x0449,0x044A,0x044B,0x044C,0x044D,0x044E,0x044F,
];
const REV = {};
for(let b=0x80;b<=0xFF;b++) if(CP[b-0x80]) REV[CP[b-0x80]]=b;
for(let b=0;b<0x80;b++) REV[b]=b;

function decodeOnce(str) {
  const bytes=[];
  for(let i=0;i<str.length;i++){
    const cp=str.charCodeAt(i);
    const b=REV[cp];
    if(b===undefined) return null;
    bytes.push(b);
  }
  try{ return Buffer.from(bytes).toString('utf8'); }catch(e){return null;}
}

const path='frontend/app/src/pages/participant/dashboard-tabs/ProjectTab.tsx';
let c=fs.readFileSync(path,'utf8');
// Apply double decode on runs of non-ASCII chars
let out='';
let i=0;
while(i<c.length){
  const cp=c.charCodeAt(i);
  if(cp>0x7F && cp!==0x2018&&cp!==0x2019&&cp!==0x201C&&cp!==0x201D){
    // collect non-ASCII run (may include spaces within Ukrainian words)
    let run='',j=i;
    while(j<c.length){
      const c2=c.charCodeAt(j);
      if(c2===0x0A||c2===0x0D) break; // newline ends run
      if(c2<0x80&&c2!==0x20) break;   // ASCII non-space ends run
      if(c2===0x20){
        // peek ahead - if next char is also non-ASCII, keep the space
        if(j+1<c.length&&c.charCodeAt(j+1)>0x7F) { run+=c[j]; j++; continue; }
        break;
      }
      run+=c[j]; j++;
    }
    if(run.length>0){
      const d1=decodeOnce(run);
      const d2=d1?decodeOnce(d1):null;
      if(d2&&/[\u0400-\u04FF]/.test(d2)){ out+=d2; i=j; continue; }
      if(d1&&/[\u0400-\u04FF]/.test(d1)){ out+=d1; i=j; continue; }
    }
  }
  out+=c[i]; i++;
}
fs.writeFileSync(path,out,'utf8');
